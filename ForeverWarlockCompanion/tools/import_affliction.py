"""Rebuild only Affliction from a downloaded WOWTBC Gatsby page-data.json.
Usage: python3 tools/import_affliction.py path/to/page-data.json [retrieval-date YYYY-MM-DD]
No rankings, numerical recommendations or guessed recipes are generated.
"""
import datetime, hashlib, json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[1]
raw = pathlib.Path(sys.argv[1]).read_bytes()
x = json.loads(raw)['result']['pageContext']
assert x['spec'] == 'affliction-warlock'
gear = x['bisList']['pre-raid']['gear']
slots = {'head':'Head','neck':'Neck','shoulder':'Shoulders','back':'Back','chest':'Chest','wrist':'Wrists','hands':'Hands','waist':'Waist','legs':'Legs','feet':'Feet','finger 1':'Ring1','finger 2':'Ring2','trinket 1':'Trinket1','trinket 2':'Trinket2','weapon':'MainHand','off hand':'OffHand','ranged':'Ranged'}
by_id = {g['id']:g for g in x['gearData']}
quality = {'poor':0,'common':1,'uncommon':2,'rare':3,'epic':4,'legendary':5}
def lua(x):
 if x is None: return 'nil'
 if isinstance(x,bool): return 'true' if x else 'false'
 if isinstance(x,(int,float)): return str(x)
 if isinstance(x,str):
  # Lua 5.1 has decimal byte escapes, not JSON's Unicode escapes.
  return '"'+''.join('\\\\' if ch=='\\' else '\\"' if ch=='"' else ('\\%03d'%ord(ch)) if ord(ch)<32 else ch for ch in x)+'"'
 if isinstance(x,list): return '{'+','.join(lua(v) for v in x)+'}'
 if isinstance(x,dict): return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in x.items())+'}'
 raise TypeError(x)
items, catalog = {}, {}
for source_slot, rows in gear.items():
 assert source_slot in slots
 ids = []
 for row in rows:
  item_id = row['id']; g = by_id.get(item_id, {})
  assert isinstance(item_id,int) and item_id > 0 and g.get('name') == row['name']
  item = dict(id=item_id, name=row['name'], source=g.get('source','Unknown'),sourceType=g.get('source_type','Unknown'),zone=g.get('zone') or g.get('source_type') or 'Unknown', quality=quality.get(g.get('rarity'),1), icon='Interface\\Icons\\'+g.get('icon','INV_Misc_QuestionMark'), provenance='imported_unranked',reference='https://wowtbc.gg/warcraftforever/bis-list/affliction-warlock/')
  item['sourceStats'] = {**g.get('special_stats',{}),**g.get('primary_stats',{}),**g.get('secondary_stats',{})}
  items[item_id] = item; ids.append(item_id)
 catalog[slots[source_slot]] = ids
lines=['-- Generated by tools/import_affliction.py. Order is source order, NOT performance.','local D = FWC.Data','D.items = {']
lines += ['    ['+str(item_id)+'] = '+lua(item)+',' for item_id,item in items.items()]
lines += ['}', 'D.catalogs = { ["WARLOCK:Affliction"] = { ["Pre-BiS"] = {']
lines += ['    ['+lua(slot)+'] = '+lua(ids)+',' for slot,ids in catalog.items()]
lines += ['}, ["BiS"] = {} } }']
(root/'Data'/'Affliction.lua').write_text('\n'.join(lines)+'\n')
recipes = []
for item in items.values():
 if item['source']=='Tailoring' and item['sourceType']=='Crafted':
  recipes.append(dict(key='item:'+str(item['id']),name=item['name'],profession='Tailoring',itemID=item['id'],provenance='pending_recipe',reference=item['reference']))
wanted={e['id'] for e in x['bisList']['pre-raid']['enchants'].values()}
for e in x['enchantsData']:
 if e['id'] in wanted and e.get('source') == 'Enchanting':
  reagents=[dict(name=r['name'],qty=r['count']) for r in e.get('reagents',[]) if isinstance(r.get('count'),int) and r['count'] > 0]
  recipes.append(dict(key='spell:'+str(e['id']),spellID=e['id'],name=e['name'],profession='Enchanting',reagents=reagents or None,provenance='imported_recipe',reference='https://wowtbc.gg/warcraftforever/bis-list/affliction-warlock/'))
recipes.insert(0,dict(key='mooncloth',name='Mooncloth',profession='Tailoring',reagents=[dict(name='Felcloth',qty=2)],estimatedCooldown=95*3600,provenance='legacy_unverified',reference='Imported addon v2.1.0; confirm recipe/cooldown in game'))
(root/'Data'/'Recipes.lua').write_text('-- Imported costs carry provenance; missing costs remain unknown.\nFWC.Data.recipes = {\n'+''.join('    '+lua(r)+',\n' for r in recipes)+'}\n')
manifest=dict(url='https://wowtbc.gg/page-data/warcraftforever/bis-list/affliction-warlock/page-data.json',sha256=hashlib.sha256(raw).hexdigest(),retrieved=sys.argv[2] if len(sys.argv)>2 else datetime.date.today().isoformat(),unique_items=len(items),slot_candidates=sum(map(len,catalog.values())),head_candidates=len(catalog['Head']),recipes=len(recipes),ranking='none',mode='Pre-BiS',spec='WARLOCK:Affliction')
(root/'docs'/'import-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest))
